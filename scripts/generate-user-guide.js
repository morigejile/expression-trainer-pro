'use strict';
const fs=require('node:fs'),path=require('node:path');

// The Markdown remains the content source; runtime blocks need no network or Markdown dependency.
function generate(markdown){
 const lines=markdown.replace(/\r\n/g,'\n').split('\n'),blocks=[];
 const cells=line=>line.trim().replace(/^\||\|$/g,'').split('|').map(cell=>cell.trim());
 for(let i=0;i<lines.length;){
  const line=lines[i].trim();if(!line){i++;continue;}
  const heading=/^(#{1,3}) (.+)$/.exec(line);
  if(heading){blocks.push({type:'heading',level:heading[1].length,text:heading[2]});i++;continue;}
  if(line.startsWith('|')){
   const rows=[];while(i<lines.length&&lines[i].trim().startsWith('|')){const row=cells(lines[i++]);if(!row.every(cell=>/^:?-+:?$/.test(cell)))rows.push(row);}
   blocks.push({type:'table',rows});continue;
  }
  if(/^(?:\d+\. |[-*] )/.test(line)){
   const ordered=/^\d+\. /.test(line),items=[];
   while(i<lines.length&&(ordered?/^\d+\. /:/^[-*] /).test(lines[i].trim()))items.push(lines[i++].trim().replace(/^(?:\d+\. |[-*] )/,''));
   blocks.push({type:'list',ordered,items});continue;
  }
  const paragraph=[];while(i<lines.length&&lines[i].trim())paragraph.push(lines[i++].trim());
  blocks.push({type:'paragraph',text:paragraph.join(' ')});
 }
 return '// Generated by scripts/generate-user-guide.js from docs/guides/deepseek-first-use.md.\n'+
  '(function(root){const guide='+JSON.stringify(blocks,null,2)+';if(typeof module===\'object\'&&module.exports)module.exports=guide;else root.DeepSeekGuide=guide;})(typeof globalThis!==\'undefined\'?globalThis:this);\n';
}
if(require.main===module){
 const root=path.resolve(__dirname,'..'),target=path.join(root,'src/deepseek-guide.js');
 const output=generate(fs.readFileSync(path.join(root,'docs/guides/deepseek-first-use.md'),'utf8'));
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output){console.error('Bundled user guide is stale; run node scripts/generate-user-guide.js');process.exitCode=1;}}
 else fs.writeFileSync(target,output);
}
module.exports={generate};
